import java.io.ByteArrayInputStream;
import java.io.DataInputStream;
import java.io.IOException;
import java.math.BigDecimal;
import java.nio.ByteBuffer;
import java.nio.charset.CharacterCodingException;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.TreeMap;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Build step of the LuxLabs release profile. For every file under the upstream directory
 * it checks that the resource generated by the build has the same content as the copy
 * taken from the upstream v1.5.22.RELEASE jar. Only when every file passes, the
 * generated files are replaced with the upstream copies, so that the jar carries the
 * upstream bytes. A missing, unreadable or different generated resource fails the build
 * and no file is replaced.
 * <p>
 * Equivalence: {@code Log4j2Plugins.dat}, the same plugin entries; JSON (strict RFC
 * 8259 syntax, UTF-8), the same objects with members and array elements in any order
 * and numbers compared by value; {@code .properties}, the same keys and values; any
 * other file, the same bytes.
 * <p>
 * Usage: {@code java UpstreamResources <classes directory> <upstream directory>}.
 */
public final class UpstreamResources {

	private UpstreamResources() {
	}

	public static void main(String[] args) throws IOException {
		if (args.length != 2) {
			throw new IllegalArgumentException("Usage: UpstreamResources <classes directory> <upstream directory>");
		}
		for (String replaced : run(Paths.get(args[0]), Paths.get(args[1]))) {
			System.out.println("[luxlabs] " + replaced + ": generated content equivalent to upstream "
					+ "v1.5.22.RELEASE, upstream bytes used");
		}
	}

	/**
	 * Check every upstream file and, only if all of them pass, replace the generated
	 * files.
	 * @param classes the directory with the generated resources
	 * @param upstream the directory with the upstream copies
	 * @return the replaced files, relative to the directories
	 * @throws IOException on I/O errors
	 * @throws IllegalStateException if a generated resource is missing, invalid or
	 * different; no file is replaced
	 */
	static List<String> run(Path classes, Path upstream) throws IOException {
		if (!Files.isDirectory(upstream)) {
			throw new IllegalStateException("Upstream resources not found: " + upstream);
		}
		List<Path> files;
		try (Stream<Path> stream = Files.walk(upstream)) {
			files = stream.filter(Files::isRegularFile).sorted().collect(Collectors.toList());
		}
		if (files.isEmpty()) {
			throw new IllegalStateException("No upstream resources in " + upstream);
		}
		List<String> failures = new ArrayList<>();
		for (Path file : files) {
			String relative = upstream.relativize(file).toString();
			Path generated = classes.resolve(relative);
			if (!Files.isRegularFile(generated)) {
				failures.add(relative + ": not generated by the build");
				continue;
			}
			try {
				String difference = difference(relative, Files.readAllBytes(file), Files.readAllBytes(generated));
				if (difference != null) {
					failures.add(relative + ": " + difference);
				}
			}
			catch (IOException | RuntimeException ex) {
				failures.add(relative + ": " + ex.getMessage());
			}
		}
		if (!failures.isEmpty()) {
			for (String failure : failures) {
				System.err.println("[luxlabs] " + failure);
			}
			throw new IllegalStateException("Generated resources differ from upstream v1.5.22.RELEASE, "
					+ "no file replaced: " + String.join("; ", failures));
		}
		List<String> replaced = new ArrayList<>();
		for (Path file : files) {
			String relative = upstream.relativize(file).toString();
			Files.copy(file, classes.resolve(relative), StandardCopyOption.REPLACE_EXISTING);
			replaced.add(relative);
		}
		return replaced;
	}

	static String difference(String name, byte[] upstream, byte[] generated) throws IOException {
		Object expected;
		Object actual;
		if (name.endsWith("Log4j2Plugins.dat")) {
			expected = log4jPlugins(upstream);
			actual = log4jPlugins(generated);
		}
		else if (name.endsWith(".json")) {
			expected = Json.canonical(Json.parse(utf8(upstream, "upstream")));
			actual = Json.canonical(Json.parse(utf8(generated, "generated")));
		}
		else if (name.endsWith(".properties")) {
			expected = properties(upstream);
			actual = properties(generated);
		}
		else {
			expected = new String(upstream, StandardCharsets.ISO_8859_1);
			actual = new String(generated, StandardCharsets.ISO_8859_1);
		}
		return expected.equals(actual) ? null : "content differs";
	}

	static String utf8(byte[] bytes, String description) {
		try {
			return StandardCharsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPORT)
					.onUnmappableCharacter(CodingErrorAction.REPORT).decode(ByteBuffer.wrap(bytes)).toString();
		}
		catch (CharacterCodingException ex) {
			throw new IllegalStateException("Invalid UTF-8 in the " + description + " JSON", ex);
		}
	}

	/**
	 * Plugin entries of a Log4j 2 plugin cache, in the format written by
	 * {@code PluginCache.writeCache}: number of categories; for each category its name
	 * and number of entries; for each entry key, class name, name, printable and defer.
	 */
	static List<String> log4jPlugins(byte[] bytes) throws IOException {
		List<String> entries = new ArrayList<>();
		try (DataInputStream in = new DataInputStream(new ByteArrayInputStream(bytes))) {
			int categories = in.readInt();
			for (int i = 0; i < categories; i++) {
				String category = in.readUTF();
				int count = in.readInt();
				for (int j = 0; j < count; j++) {
					entries.add(category + "|" + in.readUTF() + "|" + in.readUTF() + "|" + in.readUTF() + "|"
							+ in.readBoolean() + "|" + in.readBoolean());
				}
			}
			if (in.read() != -1) {
				throw new IOException("Unexpected data after the plugin entries");
			}
		}
		Collections.sort(entries);
		return entries;
	}

	static Map<String, String> properties(byte[] bytes) throws IOException {
		Properties properties = new Properties();
		properties.load(new ByteArrayInputStream(bytes));
		Map<String, String> result = new TreeMap<>();
		for (String key : properties.stringPropertyNames()) {
			result.put(key, properties.getProperty(key));
		}
		return result;
	}

	/**
	 * Strict JSON reader (RFC 8259) and canonical form. Values: {@link LinkedHashMap}
	 * (duplicate member names rejected), {@link List}, {@link String}, {@link BigDecimal},
	 * {@link Boolean} and {@link #NULL}.
	 */
	static final class Json {

		static final Object NULL = new Object() {

			@Override
			public String toString() {
				return "null";
			}

		};

		private final String text;

		private int position;

		private Json(String text) {
			this.text = text;
		}

		static Object parse(String text) {
			Json json = new Json(text);
			Object value = json.value();
			json.skipWhitespace();
			if (json.position != text.length()) {
				throw json.error("Unexpected content after the JSON value");
			}
			return value;
		}

		/**
		 * Canonical form: members sorted by name, array elements sorted, numbers by
		 * value.
		 */
		static String canonical(Object value) {
			if (value instanceof Map) {
				TreeMap<String, String> members = new TreeMap<>();
				for (Map.Entry<?, ?> member : ((Map<?, ?>) value).entrySet()) {
					members.put((String) member.getKey(), canonical(member.getValue()));
				}
				StringBuilder result = new StringBuilder("{");
				for (Map.Entry<String, String> member : members.entrySet()) {
					if (result.length() > 1) {
						result.append(',');
					}
					result.append(quote(member.getKey())).append(':').append(member.getValue());
				}
				return result.append('}').toString();
			}
			if (value instanceof List) {
				List<String> elements = new ArrayList<>();
				for (Object element : (List<?>) value) {
					elements.add(canonical(element));
				}
				Collections.sort(elements);
				return "[" + String.join(",", elements) + "]";
			}
			if (value instanceof String) {
				return quote((String) value);
			}
			if (value instanceof BigDecimal) {
				BigDecimal number = (BigDecimal) value;
				return (number.signum() == 0) ? "0" : number.stripTrailingZeros().toPlainString();
			}
			return String.valueOf(value);
		}

		/**
		 * Compact JSON text of a value, in its own member and element order.
		 */
		static String write(Object value) {
			if (value instanceof Map) {
				StringBuilder result = new StringBuilder("{");
				for (Map.Entry<?, ?> member : ((Map<?, ?>) value).entrySet()) {
					if (result.length() > 1) {
						result.append(',');
					}
					result.append(quote((String) member.getKey())).append(':').append(write(member.getValue()));
				}
				return result.append('}').toString();
			}
			if (value instanceof List) {
				List<String> elements = new ArrayList<>();
				for (Object element : (List<?>) value) {
					elements.add(write(element));
				}
				return "[" + String.join(",", elements) + "]";
			}
			if (value instanceof String) {
				return quote((String) value);
			}
			if (value instanceof BigDecimal) {
				return ((BigDecimal) value).toString();
			}
			return String.valueOf(value);
		}

		private Object value() {
			skipWhitespace();
			char c = peek();
			switch (c) {
				case '{':
					return object();
				case '[':
					return array();
				case '"':
					return string();
				case 't':
					return literal("true", Boolean.TRUE);
				case 'f':
					return literal("false", Boolean.FALSE);
				case 'n':
					return literal("null", NULL);
				default:
					if (c == '-' || (c >= '0' && c <= '9')) {
						return number();
					}
					throw error("Unexpected character");
			}
		}

		private Map<String, Object> object() {
			expect('{');
			Map<String, Object> members = new LinkedHashMap<>();
			skipWhitespace();
			if (peek() == '}') {
				this.position++;
				return members;
			}
			while (true) {
				skipWhitespace();
				if (peek() != '"') {
					throw error("Expected a member name");
				}
				String name = string();
				skipWhitespace();
				expect(':');
				if (members.containsKey(name)) {
					throw error("Duplicate member " + name);
				}
				members.put(name, value());
				skipWhitespace();
				if (peek() == ',') {
					this.position++;
					continue;
				}
				expect('}');
				return members;
			}
		}

		private List<Object> array() {
			expect('[');
			List<Object> elements = new ArrayList<>();
			skipWhitespace();
			if (peek() == ']') {
				this.position++;
				return elements;
			}
			while (true) {
				elements.add(value());
				skipWhitespace();
				if (peek() == ',') {
					this.position++;
					continue;
				}
				expect(']');
				return elements;
			}
		}

		private String string() {
			expect('"');
			StringBuilder result = new StringBuilder();
			while (true) {
				char c = next();
				if (c == '"') {
					return result.toString();
				}
				if (c < 0x20) {
					this.position--;
					throw error("Unescaped control character U+" + String.format("%04X", (int) c) + " in a string");
				}
				if (c != '\\') {
					result.append(c);
					continue;
				}
				char escape = next();
				switch (escape) {
					case '"':
					case '\\':
					case '/':
						result.append(escape);
						break;
					case 'b':
						result.append('\b');
						break;
					case 'f':
						result.append('\f');
						break;
					case 'n':
						result.append('\n');
						break;
					case 'r':
						result.append('\r');
						break;
					case 't':
						result.append('\t');
						break;
					case 'u':
						int code = 0;
						for (int i = 0; i < 4; i++) {
							int digit = Character.digit(next(), 16);
							if (digit < 0 || !isAsciiHexDigit(this.text.charAt(this.position - 1))) {
								this.position--;
								throw error("Invalid hexadecimal digit in a \\u escape");
							}
							code = code * 16 + digit;
						}
						result.append((char) code);
						break;
					default:
						this.position--;
						throw error("Invalid escape \\" + escape);
				}
			}
		}

		private static boolean isAsciiHexDigit(char c) {
			return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F');
		}

		/**
		 * {@code number = [ minus ] int [ frac ] [ exp ]}, {@code int = zero / ( digit1-9
		 * *DIGIT )}, {@code frac = decimal-point 1*DIGIT},
		 * {@code exp = e [ minus / plus ] 1*DIGIT}.
		 */
		private BigDecimal number() {
			int start = this.position;
			if (peekOrEnd() == '-') {
				this.position++;
			}
			char first = peekOrEnd();
			if (first == '0') {
				this.position++;
			}
			else if (first >= '1' && first <= '9') {
				digits();
			}
			else {
				throw error("Invalid number");
			}
			if (peekOrEnd() == '.') {
				this.position++;
				if (digits() == 0) {
					throw error("Invalid number: digits expected after the decimal point");
				}
			}
			char e = peekOrEnd();
			if (e == 'e' || e == 'E') {
				this.position++;
				char sign = peekOrEnd();
				if (sign == '+' || sign == '-') {
					this.position++;
				}
				if (digits() == 0) {
					throw error("Invalid number: digits expected in the exponent");
				}
			}
			char after = peekOrEnd();
			if (after >= '0' && after <= '9') {
				throw error("Invalid number: leading zero");
			}
			return new BigDecimal(this.text.substring(start, this.position));
		}

		private int digits() {
			int start = this.position;
			while (this.position < this.text.length() && this.text.charAt(this.position) >= '0'
					&& this.text.charAt(this.position) <= '9') {
				this.position++;
			}
			return this.position - start;
		}

		private Object literal(String literal, Object value) {
			if (!this.text.startsWith(literal, this.position)) {
				throw error("Invalid literal");
			}
			this.position += literal.length();
			return value;
		}

		static String quote(String value) {
			StringBuilder result = new StringBuilder("\"");
			for (char c : value.toCharArray()) {
				if (c == '"' || c == '\\') {
					result.append('\\').append(c);
				}
				else if (c < 0x20) {
					result.append(String.format("\\u%04x", (int) c));
				}
				else {
					result.append(c);
				}
			}
			return result.append('"').toString();
		}

		/**
		 * JSON whitespace only: space, horizontal tab, line feed and carriage return.
		 */
		private void skipWhitespace() {
			while (this.position < this.text.length()) {
				char c = this.text.charAt(this.position);
				if (c != ' ' && c != '\t' && c != '\n' && c != '\r') {
					return;
				}
				this.position++;
			}
		}

		private char peekOrEnd() {
			return (this.position < this.text.length()) ? this.text.charAt(this.position) : '\0';
		}

		private char peek() {
			if (this.position >= this.text.length()) {
				throw error("Unexpected end");
			}
			return this.text.charAt(this.position);
		}

		private char next() {
			char c = peek();
			this.position++;
			return c;
		}

		private void expect(char expected) {
			if (peek() != expected) {
				throw error("Expected '" + expected + "'");
			}
			this.position++;
		}

		private IllegalStateException error(String message) {
			return new IllegalStateException("Invalid JSON: " + message + " at offset " + this.position);
		}

	}

}
